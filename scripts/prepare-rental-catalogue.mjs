// Produces reviewable draft-only SQL. Never connects to a database.
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
const root=process.cwd();
function load(file){const loaded={exports:{}};const code=ts.transpileModule(fs.readFileSync(file,'utf8'),{compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2022}}).outputText;new Function('require','module','exports',code)(name=>{if(!name.startsWith('.'))throw Error('Unexpected dependency');return load(path.resolve(path.dirname(file),name))},loaded,loaded.exports);return loaded.exports}
const {rentalCatalogue,catalogueRentalConfig}=load(path.join(root,'src/lib/rentals/catalogue.ts'));
const quote=v=>"'"+v.replaceAll("'","''")+"'";
let sql=`-- GENERATED by node scripts/prepare-rental-catalogue.mjs. REVIEW before execution.
-- psql -X -v ON_ERROR_STOP=1 -v property_id=REVIEWED_PROPERTY_UUID -f this-file.sql
-- Target the existing project only. No changes to existing products or bookings.
\\if :{?property_id}
\\else
\\echo 'Supply the reviewed property_id; no database change performed.'
\\quit 3
\\endif
BEGIN;
SELECT set_config('borealis.seed_property', :'property_id', true);
SELECT pg_advisory_xact_lock(hashtext(:'property_id'));
DO $$ BEGIN IF NOT EXISTS(SELECT 1 FROM public.properties WHERE id=current_setting('borealis.seed_property')::uuid) THEN RAISE EXCEPTION 'Unknown property'; END IF; END $$;
`;
for(const p of rentalCatalogue){
 const c=catalogueRentalConfig(p.key);
 const names=p.key==='sup'?['sup rental','paddle rental','paddle rental koman lake']:p.key==='single_kayak'?['single kayak','single kayak rental']:p.key==='double_kayak'?['double kayak','double kayak rental']:['boat rental','boat'];
 sql+=`\n-- ${p.name}: reuse a matching existing record through Admin rather than creating a duplicate.
INSERT INTO public.experiences(property_id,name,slug,description,short_description,full_description,price,currency,pricing_type,duration_label,availability_mode,active,bookable,book_independently,status,is_visible,rental_config)
SELECT current_setting('borealis.seed_property')::uuid,${quote(p.name)},${quote(p.slug)},${quote(p.name+' at Borealis. Availability and rules require owner review.')},${quote(p.name+' at Borealis.')},${quote(c.policies.safety)},NULL,'EUR','on_request','Hourly / daily','always',false,false,false,'draft',true,${quote(JSON.stringify(c))}::jsonb
WHERE NOT EXISTS(SELECT 1 FROM public.experiences WHERE property_id=current_setting('borealis.seed_property')::uuid AND (slug=${quote(p.slug)} OR lower(trim(name)) IN (${names.map(quote).join(',')})));
`;
}
sql+=`\n-- Review all existing products, including Paddle Rental and Personalized Dinner.
SELECT id,name,slug,status,bookable,book_independently,rental_config IS NOT NULL AS is_rental FROM public.experiences WHERE property_id=current_setting('borealis.seed_property')::uuid ORDER BY sort_order,name;
COMMIT;
`;
fs.writeFileSync(path.join(root,'database/seeds/20261103_rental_catalogue.sql'),sql);
console.log('Prepared draft-only catalogue SQL; no database connection made.');
